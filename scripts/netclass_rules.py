#!/usr/bin/env python3
"""Generate KiCad net classes and track-width DRC rules from scripts/netclasses.toml.

For every class in the config:
  * track width comes from the design current (IPC-2221, external layer,
    copper thickness read from the board stackup, temperature rise from the config),
  * clearance comes from the highest voltage on the class (IPC-2221B table 6-1,
    column B2: external, uncoated, sea level), never below the Default clearance.

What it writes:
  * <project>.kicad_pro: the classes, a pattern per net assigning it to its class,
    and the computed widths added to the predefined track widths (W key in the router).
  * <project>.kicad_dru: between the BEGIN/END markers, one rule per class making the
    class width the DRC minimum and the router width, then the pad exceptions:
    wherever a class's track would be wider than a pad it lands on, tracks of that
    class inside that footprint's courtyard may neck down to the pad's narrow side.
    The router starts at that width when you start a track on such a pad.
    Anything outside the markers is kept.

Run from anywhere:  python3 scripts/netclass_rules.py   (KiCad must not have the project open)
"""
import json
import math
import re
import sys
import tomllib
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "scripts" / "netclasses.toml"
BEGIN = "# BEGIN generated by scripts/netclass_rules.py: edit scripts/netclasses.toml, not this block"
END = "# END generated by scripts/netclass_rules.py"

# IPC-2221B table 6-1, B2 (external conductors, uncoated, sea level to 3050 m): (max volts, mm)
IPC_B2 = [(15, 0.1), (30, 0.1), (50, 0.6), (100, 0.6), (150, 0.6), (170, 1.25),
          (250, 1.25), (300, 1.25), (500, 2.5)]


# ---------------------------------------------------------------- s-expression reading
def parse_sexp(text):
    tok = re.compile(r'\(|\)|"(?:[^"\\]|\\.)*"|[^\s()]+')
    stack = [[]]
    for m in tok.finditer(text):
        t = m.group()
        if t == "(":
            stack.append([])
        elif t == ")":
            node = stack.pop()
            stack[-1].append(node)
        else:
            stack[-1].append(t[1:-1] if t[0] == '"' else t)
    return stack[0][0]


def children(node, key):
    return [c for c in node if isinstance(c, list) and c and c[0] == key]


def child(node, key):
    found = children(node, key)
    return found[0] if found else None


def read_board(path):
    board = parse_sexp(path.read_text())
    stackup = child(child(board, "setup"), "stackup")
    copper = [child(l, "thickness") for l in children(stackup, "layer")
              if (child(l, "type") or [None, None])[1] == "copper"] if stackup else []
    outer_mm = float(copper[0][1]) if copper and copper[0] else 0.035
    footprints = []
    for fp in children(board, "footprint"):
        ref = next((p[2] for p in children(fp, "property") if p[1] == "Reference"), "")
        at = child(fp, "at")
        fp_angle = float(at[3]) if len(at) > 3 else 0.0
        pads = []
        for pad in children(fp, "pad"):
            net = child(pad, "net")
            size = child(pad, "size")
            if net and size:
                w, h = float(size[1]), float(size[2])
                pads.append((net[-1], pad[3], w, h, pad_corners(pad, w, h, fp_angle)))
        footprints.append(dict(ref=ref, pads=pads, courtyard=courtyard_bbox(fp)))
    return outer_mm, footprints


def pad_corners(pad, w, h, fp_angle):
    """Pad rectangle corners in footprint coordinates. Board files store the pad
    angle including the footprint's own rotation, so that is taken off first."""
    at = child(pad, "at")
    x, y = float(at[1]), float(at[2])
    a = math.radians((float(at[3]) if len(at) > 3 else 0.0) - fp_angle)
    return [(x + dx * math.cos(a) + dy * math.sin(a), y - dx * math.sin(a) + dy * math.cos(a))
            for dx, dy in ((w / 2, h / 2), (-w / 2, h / 2), (w / 2, -h / 2), (-w / 2, -h / 2))]


def courtyard_bbox(fp):
    """Bounding box of the footprint's courtyard graphics, or None without a courtyard."""
    pts = []
    for g in fp:
        if not (isinstance(g, list) and g and str(g[0]).startswith("fp_")):
            continue
        layer = child(g, "layer")
        if not layer or "CrtYd" not in layer[1]:
            continue
        if g[0] == "fp_circle":
            c, e = child(g, "center"), child(g, "end")
            r = math.dist((float(c[1]), float(c[2])), (float(e[1]), float(e[2])))
            pts += [(float(c[1]) - r, float(c[2]) - r), (float(c[1]) + r, float(c[2]) + r)]
        for key in ("start", "end", "mid"):
            p = child(g, key)
            if p and g[0] != "fp_circle":
                pts.append((float(p[1]), float(p[2])))
        for xy in children(child(g, "pts") or [], "xy"):
            pts.append((float(xy[1]), float(xy[2])))
    if not pts:
        return None
    xs, ys = zip(*pts)
    return min(xs), min(ys), max(xs), max(ys)


def inside(corners, box, tol=0.01):
    return all(box[0] - tol <= x <= box[2] + tol and box[1] - tol <= y <= box[3] + tol
               for x, y in corners)


# ---------------------------------------------------------------- sizing
def ipc2221_width_mm(current_a, rise_c, copper_mm):
    """IPC-2221 external conductor: I = 0.048 * dT^0.44 * A^0.725, A in mil^2."""
    area_mil2 = (current_a / (0.048 * rise_c ** 0.44)) ** (1 / 0.725)
    return area_mil2 / (copper_mm / 0.0254) * 0.0254


def ceil_to(x, step):
    return round(math.ceil(round(x / step, 6)) * step, 4)


def floor_to(x, step):
    return round(math.floor(round(x / step, 6)) * step, 4)


def ipc_clearance_mm(volts):
    for vmax, mm in IPC_B2:
        if volts <= vmax:
            return mm
    sys.exit(f"{volts} V is above the IPC-2221B table; set clearance by hand")


def mm(x):
    return f"{x:g}mm"


# ---------------------------------------------------------------- main
def main():
    cfg = tomllib.loads(CONFIG.read_text())
    design = cfg["design"]
    name = design["project"]
    pro_path = ROOT / f"{name}.kicad_pro"
    dru_path = ROOT / f"{name}.kicad_dru"
    if list(ROOT.glob(f"~{name}.kicad_pcb.lck")) or list(ROOT.glob(f"~{name}.kicad_pro.lck")):
        sys.exit("The project looks open in KiCad (lock file present): close it first, "
                 "or KiCad will overwrite what this script writes.")

    copper_mm, footprints = read_board(ROOT / f"{name}.kicad_pcb")
    pro = json.loads(pro_path.read_text())
    ns = pro["net_settings"]
    default = next(c for c in ns["classes"] if c["name"] == "Default")
    rise = design["temp_rise_c"]
    step = design.get("round_mm", 0.05)
    neck_min = design["min_track_mm"]

    board_nets = {n for fp in footprints for n, *_ in fp["pads"]}
    net_class, classes, problems = {}, [], []
    for c in cfg["class"]:
        width = max(ceil_to(ipc2221_width_mm(c["current_a"], rise, copper_mm), step),
                    default["track_width"])
        clearance = max(ipc_clearance_mm(c["voltage_v"]), default["clearance"])
        classes.append(dict(c, width=width, clearance=clearance))
        for n in c["nets"]:
            if n not in board_nets:
                problems.append(f"{c['name']}: net {n!r} is not on the board")
            if n in net_class:
                problems.append(f"net {n!r} is in both {net_class[n]} and {c['name']}")
            net_class[n] = c["name"]
    if problems:
        sys.exit("netclasses.toml does not match the board:\n  " + "\n  ".join(problems))

    # pad exceptions: per class, the footprints whose pads on that class are narrower
    # than the class width, grouped by the neck width they need
    # (the exception is scoped by the footprint's courtyard, so the courtyard must
    # cover those pads entirely, or a track on the outer end of a pad is not covered)
    necks, bad = [], set()
    for c in classes:
        by_neck = defaultdict(set)
        for fp in footprints:
            mine = [p for p in fp["pads"] if net_class.get(p[0]) == c["name"]]
            sizes = [min(w, h) for _, _, w, h, _ in mine]
            if sizes and min(sizes) < c["width"]:
                if not fp["courtyard"]:
                    bad.add(f"{fp['ref']}: no courtyard")
                elif not all(inside(corners, fp["courtyard"]) for *_, corners in mine):
                    bad.add(f"{fp['ref']}: courtyard does not cover its {c['name']} pads")
                narrow = min(sizes)
                neck = floor_to(narrow, step) if narrow >= neck_min + step else max(
                    floor_to(narrow, 0.01), min(neck_min, narrow))
                by_neck[neck].add(fp["ref"])
        # widest first: where two courtyards overlap the later (narrower) rule wins,
        # so the exception never asks for more than the smaller pad allows
        for neck, refs in sorted(by_neck.items(), reverse=True):
            necks.append((c["name"], c["width"], neck, sorted(refs)))
    if bad:
        sys.exit("These footprints have pads that need a neck-down exception, which is scoped "
                 "by the courtyard. Fix the courtyard (footprint editor), then rerun:\n  "
                 + "\n  ".join(sorted(bad)))

    # ---- .kicad_pro
    generated = {c["name"] for c in classes}
    kept = [c for c in ns["classes"] if c["name"] not in generated]
    for prio, c in enumerate(classes):
        kept.append(dict(default, name=c["name"], track_width=c["width"],
                         clearance=c["clearance"], priority=prio))
    ns["classes"] = kept
    ns["netclass_patterns"] = [p for p in ns.get("netclass_patterns", [])
                               if p["netclass"] not in generated] + [
        {"netclass": c["name"], "pattern": n} for c in classes for n in c["nets"]]
    ds = pro["board"]["design_settings"]
    widths = set(ds.get("track_widths") or []) - {0.0}
    widths |= {c["width"] for c in classes} | {n for _, _, n, _ in necks}
    # index 0 is KiCad's "use netclass width" entry
    ds["track_widths"] = [0.0] + sorted(widths)
    pro_path.write_text(json.dumps(pro, indent=2) + "\n")

    # ---- .kicad_dru
    lines = [BEGIN,
             f"# Widths: IPC-2221 external, {copper_mm * 1000:g} um copper, {rise} C rise. "
             f"Clearance: IPC-2221B B2.",
             "# Later rules win, so the pad exceptions come after the class rules."]
    for c in classes:
        lines += [f"# {c['name']}: {c['current_a']:g} A, up to {c['voltage_v']:g} V",
                  f"(rule \"{c['name']} track width\"",
                  f"  (condition \"A.hasNetclass('{c['name']}')\")",
                  f"  (constraint track_width (min {mm(c['width'])}) (opt {mm(c['width'])})))"]
    for cname, width, neck, refs in necks:
        where = " || ".join(f"A.intersectsCourtyard('{r}')" for r in refs)
        lines += [f"# {cname} pads narrower than {width:g} mm: {', '.join(refs)}",
                  f"(rule \"{cname} neck-down to {neck:g}mm at pads\"",
                  f"  (condition \"A.hasNetclass('{cname}') && ({where})\")",
                  f"  (constraint track_width (min {mm(neck)}) (opt {mm(neck)})))"]
    lines.append(END)
    block = "\n".join(lines)
    old = dru_path.read_text() if dru_path.exists() else "(version 1)\n"
    if BEGIN in old:
        new = old[:old.index(BEGIN)] + block + old[old.index(END) + len(END):]
    else:
        new = old.rstrip("\n") + "\n\n" + block + "\n"
    dru_path.write_text(new)

    for c in classes:
        print(f"{c['name']:10s} {c['current_a']:>4g} A {c['voltage_v']:>5g} V  "
              f"width {c['width']:g} mm  clearance {c['clearance']:g} mm  ({len(c['nets'])} nets)")
    for cname, width, neck, refs in necks:
        print(f"  {cname} neck-down {neck:g} mm at {', '.join(refs)}")


if __name__ == "__main__":
    main()
